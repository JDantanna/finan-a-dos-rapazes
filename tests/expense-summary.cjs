const assert=require('node:assert/strict');
const {summarizeExpenses}=require('../dist/expense-summary.js');
const accounts=[{name:'Nubank crédito',type:'credit'},{name:'Nubank conta',type:'checking'},{name:'Flash',type:'benefit'}];
const expense=(source,cents)=>({entry:{source,cents,kind:'expense'}});
const result=summarizeExpenses([expense('Nubank crédito',25001),expense('Nubank crédito',100),expense('Nubank conta',80000),expense('Flash',30000),expense('Antiga',501),{entry:{kind:'income',source:'Nubank conta',cents:1000000}}],accounts);
assert.equal(result.totals.credit,25101);assert.equal(result.totals.checking,80000);assert.equal(result.totals.benefit,30000);assert.equal(result.totals.unclassified,501);
assert.equal(result.items.reduce((sum,x)=>sum+x.cents,0),135602);
assert.equal(summarizeExpenses([],accounts).items.length,0);
assert.equal(summarizeExpenses([expense('__proto__',10)],[]).totals.unclassified,10);
